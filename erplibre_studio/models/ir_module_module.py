import os

from odoo import api, models
from odoo.exceptions import UserError
from odoo.modules.module import get_module_path
from odoo.tools import sql

from .. import arch as studio_arch
from .erplibre_studio_project import MARKER_FILE


class IrModuleModule(models.Model):
    _inherit = "ir.module.module"

    def button_uninstall(self):
        """Refuse to uninstall erplibre_studio, alone or with a module it
        depends on, while a project has records applied in the database
        and its generated module is not installed: without the studio,
        nothing could revert them, and their external ids would name a
        module that does not exist."""
        res = super().button_uninstall()
        studio = self.search(
            [("name", "=", "erplibre_studio"), ("state", "=", "to remove")]
        )
        if studio:
            projects = self.env["erplibre.studio.project"].sudo()._studio_applied()
            if projects:
                raise UserError(
                    self.env._(
                        "Revert the studio projects %(projects)s first, or "
                        "install their generated modules: what they applied "
                        "would stay in the database with nothing to remove it.",
                        projects=", ".join(projects.mapped("name")),
                    )
                )
        return res

    def _studio_generated(self):
        """Whether the module was generated by a studio project: a project
        makes it, or its directory holds the marker of a generation."""
        self.ensure_one()
        Project = self.env.get("erplibre.studio.project")
        if Project is not None and Project.sudo().search_count(
            [("module_name", "=", self.name)]
        ):
            return True
        path = get_module_path(self.name, display_warning=False)
        return bool(path) and os.path.isfile(os.path.join(path, MARKER_FILE))

    def _studio_count(self, table, column=None):
        cr = self.env.cr
        if not table or not sql.table_exists(cr, table):
            return 0
        query = f'SELECT count(*) FROM "{table}"'
        if column:
            if not sql.column_exists(cr, table, column):
                return 0
            query += f' WHERE "{column}" IS NOT NULL'
        cr.execute(query)
        return cr.fetchone()[0]

    def _studio_lost_models(self, names):
        """The ir.model of the module that leave the database with it: those
        all of whose external ids belong to ``names``, the modules
        uninstalled together."""
        self.ensure_one()
        data = (
            self.env["ir.model.data"]
            .sudo()
            .search([("module", "=", self.name), ("model", "=", "ir.model")])
        )
        models_ = self.env["ir.model"].sudo().browse(data.mapped("res_id")).exists()
        xmlids = models_._get_external_ids()
        return models_.filtered(
            lambda m: all(x.split(".")[0] in names for x in xmlids.get(m.id, ()))
        )

    @api.model
    def _studio_owned_ids(self, res_model, ids, names):
        """The ids of ``ids`` (records of ``res_model``) with an external id
        under one of the modules ``names``."""
        data = (
            self.env["ir.model.data"]
            .sudo()
            .search(
                [
                    ("model", "=", res_model),
                    ("res_id", "in", list(ids)),
                    ("module", "in", sorted(names)),
                ]
            )
        )
        return set(data.mapped("res_id"))

    def _studio_foreign_on(self, lost, names):
        """{kind: records} of what the database deletes with the models
        ``lost`` although no module of ``names`` owns it: the fields of the
        other models that point at them and the fields another project adds
        to them (« fields »), the access rights and record rules on them
        (« access », « rules »), and the records ``_studio_cascade_records``
        finds (« others »)."""
        self.ensure_one()
        env = self.env(su=True, context=dict(self.env.context, active_test=False))
        model_names = lost.mapped("model")
        Fields = env["ir.model.fields"]
        Project = env.get("erplibre.studio.project")
        project_fields = Project.search([]).field_ids if Project is not None else Fields
        candidates = Fields.search(
            [("relation", "in", model_names), ("model", "not in", model_names)]
        ) | (Fields.search([("model", "in", model_names)]) & project_fields)
        owned = self._studio_owned_ids("ir.model.fields", candidates.ids, names)
        result = {"fields": candidates.filtered(lambda f: f.id not in owned)}
        for kind, res_model in (("access", "ir.model.access"), ("rules", "ir.rule")):
            rows = env[res_model].search([("model_id", "in", lost.ids)])
            owned = self._studio_owned_ids(res_model, rows.ids, names)
            result[kind] = rows.filtered(lambda r, o=owned: r.id not in o)
        others = []
        if Project is not None:
            for rows in Project._studio_cascade_records(lost):
                owned = self._studio_owned_ids(rows._name, rows.ids, names)
                rows = rows.filtered(lambda r, o=owned: r.id not in o)
                if rows:
                    others.append(rows)
        result["others"] = others
        return result

    def _studio_uninstall_refusal(self, names):
        """Why the wizard refuses to uninstall the module with ``names``, or
        False: another studio project applied fields, access rights, rules
        or views on the models the module takes with it. The database would
        delete them, and that project would keep, as applied, what is gone;
        it reverts them first, or removes them from its draft and applies."""
        self.ensure_one()
        Project = self.env.get("erplibre.studio.project")
        lost = self._studio_lost_models(names)
        if Project is None or not lost:
            return False
        model_names = lost.mapped("model")
        items = []
        for project in Project.sudo().search(
            [("module_name", "not in", sorted(names))]
        ):
            touching = project.field_ids.filtered(
                lambda f: f.model in model_names or f.relation in model_names
            ).mapped(lambda f: f"{f.model}.{f.name}")
            touching += project.created_access_ids.filtered(
                lambda a: a.model_id in lost
            ).mapped("name")
            touching += project.created_rule_ids.filtered(
                lambda r: r.model_id in lost
            ).mapped("name")
            touching += project.studio_view_ids.filtered(
                lambda v: v.model in model_names
            ).mapped("name")
            if touching:
                items.append(f"{project.name} ({', '.join(sorted(touching))})")
        if not items:
            return False
        return self.env._(
            "Uninstalling %(module)s deletes what other studio projects applied "
            "on its models: %(items)s. Revert these projects first, or remove "
            "these lines from them and apply.",
            module=self.name,
            items="; ".join(items),
        )

    def _studio_uninstall_report(self, names):
        """What uninstalling the module deletes, in the shape of a studio
        removal report: the models all of whose external ids belong to
        ``names`` (the modules uninstalled together) with their records, the
        fields of the module on the models that stay with their values, its
        menus, access rights, rules, groups with their members, categories
        and relation tables; then what the database deletes with these
        models that no module of ``names`` owns (``_studio_foreign_on``),
        its owner named."""
        self.ensure_one()
        self.env.flush_all()
        Data = self.env["ir.model.data"].sudo()

        def records(res_model):
            data = Data.search([("module", "=", self.name), ("model", "=", res_model)])
            Model = self.env[res_model].sudo().with_context(active_test=False)
            if res_model == "ir.ui.menu":
                Model = Model.with_context(**{"ir.ui.menu.full_list": True})
            return Model.browse(data.mapped("res_id")).exists()

        report = {key: [] for key in ("models", "fields", "menus", "actions")}
        lost = self._studio_lost_models(names)
        foreign = self._studio_foreign_on(lost, names)
        for model in lost.sorted("model"):
            Model = self.env.get(model.model)
            table = Model._table if Model is not None else model.model.replace(".", "_")
            report["models"].append(
                {
                    "model": model.model,
                    "name": model.name,
                    "count": self._studio_count(table),
                }
            )
        removed = set(lost.mapped("model"))
        own_fields = records("ir.model.fields").filtered(
            lambda f: f.model not in removed
        )
        for field in (own_fields | foreign["fields"]).sorted(
            lambda f: (f.model, f.name)
        ):
            Model = self.env.get(field.model)
            filled = 0
            if Model is not None and field.store:
                if field.ttype == "many2many":
                    filled = self._studio_count(field.relation_table)
                elif field.ttype not in studio_arch.X2MANY_TYPES:
                    filled = self._studio_count(Model._table, field.name)
            report["fields"].append(
                {
                    "model": field.model,
                    "name": field.name,
                    "label": field.field_description,
                    "filled": filled,
                }
            )
        report["menus"] = [
            {"name": m.complete_name} for m in records("ir.ui.menu").sorted("id")
        ]
        report["actions"] = [
            {"name": a.name} for a in records("ir.actions.act_window").sorted("id")
        ]
        report["access"] = [
            {"name": a.name, "group": a.group_id.full_name or ""}
            for a in (records("ir.model.access") | foreign["access"]).sorted("name")
        ]
        report["rules"] = [
            {"name": r.name, "model": r.model_id.model}
            for r in (records("ir.rule") | foreign["rules"]).sorted("name")
        ]
        Project = self.env["erplibre.studio.project"]
        report["others"] = sorted(
            (
                {"name": Project._studio_record_label(record)}
                for rows in foreign["others"]
                for record in rows
            ),
            key=lambda item: item["name"],
        )
        report["groups"] = [
            {"name": g.full_name, "users": len(g.users)}
            for g in records("res.groups").sorted("id")
        ]
        report["categories"] = [
            {"name": c.name} for c in records("ir.module.category").sorted("id")
        ]
        report["tables"] = sorted(
            self.env["ir.model.relation"]
            .sudo()
            .search([("module", "=", self.id)])
            .mapped("name")
        )
        return report

    def module_uninstall(self):
        """Once a module a project generated is uninstalled, the project is
        back to a draft with its lines: its records left the database with
        the module. What Odoo leaves behind the models of a generated module
        goes too: their filters, the external ids of their inheritance
        (``_studio_drop_model_leftovers``), and the reflection of the
        constraints of the module that left the database with the columns
        and the tables (``_studio_drop_constraint_rows``)."""
        names = self.mapped("name")
        Project = self.env.get("erplibre.studio.project")
        studio = self.browse()
        lost = []
        if Project is not None and "erplibre_studio" not in names:
            studio = self.filtered(lambda m: m._studio_generated())
            for module in studio:
                lost += module._studio_lost_models(set(names)).mapped("model")
        res = super().module_uninstall()
        if Project is not None and "erplibre_studio" not in names:
            Project.sudo()._studio_drop_model_leftovers(lost)
            studio._studio_drop_constraint_rows()
            projects = Project.sudo().search([("module_name", "in", names)])
            projects._studio_reset_after_uninstall()
        return res

    def _studio_drop_constraint_rows(self):
        """Delete the ir.model.constraint rows of the modules whose constraint
        the database no longer has: the uninstall dropped the columns and
        the tables they were on, the foreign keys of a many2one on an
        existing model among them, but keeps the rows of the constraints it
        did not create itself."""
        if not self:
            return
        self.env.cr.execute(
            """
            DELETE FROM ir_model_constraint c
             WHERE c.module IN %s
               AND NOT EXISTS (
                   SELECT 1 FROM pg_constraint p WHERE p.conname = left(c.name, 63)
               )
            """,
            [tuple(self.ids)],
        )
        self.env["ir.model.constraint"].invalidate_model()
