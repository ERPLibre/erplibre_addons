from markupsafe import Markup, escape
from odoo import api, fields, models
from odoo.exceptions import UserError

from .erplibre_studio_report import report_html


class BaseModuleUninstall(models.TransientModel):
    """The uninstall wizard of Odoo, for a module a studio project
    generated: the report of what the uninstall deletes (its models and
    their records, its fields and their values, menus, rights, rules and
    groups), and a checkbox to tick before the button shows."""

    _inherit = "base.module.uninstall"

    studio_module_ids = fields.Many2many(
        "ir.module.module",
        compute="_compute_studio_report",
        string="Modules generated by the studio",
    )
    studio_report = fields.Html(compute="_compute_studio_report", sanitize=False)
    studio_refused = fields.Char(
        compute="_compute_studio_report", string="Why the uninstall is refused"
    )
    studio_understood = fields.Boolean(
        string="I understand that these models, their records, the fields and "
        "their values, the menus, the access rights, the rules and the groups "
        "are deleted.",
    )

    @api.depends("module_id")
    def _compute_studio_report(self):
        for wizard in self:
            modules = wizard.module_id and wizard._get_modules()
            studio = (
                modules.filtered(lambda m: m._studio_generated())
                if modules
                else modules
            )
            wizard.studio_module_ids = studio
            wizard.studio_refused = False
            if not studio:
                wizard.studio_report = False
                continue
            names = set(modules.mapped("name"))
            refusals = [module._studio_uninstall_refusal(names) for module in studio]
            wizard.studio_refused = "\n".join(r for r in refusals if r) or False
            parts = [
                Markup("<h4>%s</h4>") % escape(module.shortdesc or module.name)
                + report_html(self.env, module._studio_uninstall_report(names))
                for module in studio
            ]
            wizard.studio_report = Markup("").join(parts)

    def action_uninstall(self):
        for wizard in self:
            if wizard.studio_refused:
                raise UserError(wizard.studio_refused)
            if wizard.studio_module_ids and not wizard.studio_understood:
                raise UserError(
                    self.env._(
                        "Check « I understand » first: uninstalling %(modules)s "
                        "deletes what the report lists.",
                        modules=", ".join(wizard.studio_module_ids.mapped("name")),
                    )
                )
        return super().action_uninstall()
