// Writes visual_table_size_fixture.js from the real, shipped
// visualTableSize (geometry.js) — the single source of truth both
// geometry.test.js (JS) and test_visual_table_size_matches_js.py
// (Python) read to check that visual_table_size (event_table.py)
// keeps agreeing with it. Re-run this after any change to
// visualTableSize's own formula, including the corner solver, and
// commit the regenerated fixture in the same commit as that change —
// a hand-edited row would defeat the whole point, which is that
// nobody has to remember to keep the two sides in step by hand.
//
// Usage: node generate_visual_table_size_fixture.mjs

import {writeFileSync} from "node:fs";
import path from "node:path";
import {fileURLToPath} from "node:url";
import {
    LIST_FULL_NAME_ONE_LINE_CHARS,
    listLinePitch,
    listReservedHeight,
    listWidth,
    listWrapsToTwoLines,
    visualTableSize,
} from "../src/floor_plan/geometry.js";

const here = path.dirname(fileURLToPath(import.meta.url));

// Both shapes, both assignSeats states, seat counts spanning the range
// where each shape stops returning its own minimum size — the rim term
// overtakes that minimum at 15 seats on a round table, at 11 on a
// square one — and well past it in both directions, up to a seat count
// far past anything this module's own indicators (03 §8) target. Both
// assignSeats states are still swept: they now pin that the two return
// the SAME size, where they once pinned two different ones.
const SEAT_COUNTS = [2, 4, 8, 10, 11, 12, 14, 15, 16, 17, 20, 25, 30, 45, 50, 51, 52, 60, 100, 200, 500, 1000];

const rows = [];
for (const shape of ["round", "square"]) {
    for (const assignSeats of [true, false]) {
        for (const seatCount of SEAT_COUNTS) {
            const {width, height} = visualTableSize(shape, seatCount, assignSeats, false);
            rows.push({shape, seatCount, assignSeats, showCompany: false, width, height});
        }
    }
}
// A handful of showCompany spot checks, both shapes, one seat count on
// each side of the range above. showCompany no longer changes any term
// of the size: these rows pin exactly that, so a full sweep would only
// repeat it.
for (const shape of ["round", "square"]) {
    for (const seatCount of [8, 20]) {
        const {width, height} = visualTableSize(shape, seatCount, false, true);
        rows.push({shape, seatCount, assignSeats: false, showCompany: true, width, height});
    }
}

const header = `/** @odoo-module **/
// Copyright 2026 TechnoLibre - Mathieu Benoit
// License AGPL-3.0 or later (http://www.gnu.org/licenses/agpl.html).

// GENERATED by generate_visual_table_size_fixture.mjs, not
// hand-written: every row is visualTableSize's own output
// (geometry.js), called for real. Read by BOTH sides of the twin this
// pins together — geometry.test.js (JS) via a plain import, and
// tests/test_visual_table_size_matches_js.py (Python) via a small,
// exact text-extraction of the array below, never a JS parser — so
// visual_table_size (event_table.py) and visualTableSize (JS) failing
// to agree on any one of these rows fails a test on ITS OWN side, not
// only a comment or a report that says they agreed once. Written here
// as plain JSON (quoted keys, no trailing comma), but the Python side
// tolerates ./script/maintenance/format.sh's own, idiomatic JS
// reformatting of it too (bare keys, a trailing comma) — see its own
// comment for why. Regenerate this whole file with the script named
// above instead of hand-editing a row, including after any change to
// visualTableSize's own formula.
export const VISUAL_TABLE_SIZE_FIXTURE = `;

// The name list's own reservation, the OTHER arithmetic written twice:
// listWidth, listWrapsToTwoLines and listLinePitch here, their
// list_width, list_wraps_to_two_lines and list_line_pitch in
// event_table.py. Both options are booleans and are swept exhaustively;
// the label length is swept at the five points where the answer can
// change — no label at all, one character under the threshold, exactly
// on it, one over, and far past — since a threshold is wrong in exactly
// two ways, off by one on either side, and only the two rows that
// straddle it can say so.
const LABEL_LENGTHS = [
    0,
    LIST_FULL_NAME_ONE_LINE_CHARS - 1,
    LIST_FULL_NAME_ONE_LINE_CHARS,
    LIST_FULL_NAME_ONE_LINE_CHARS + 1,
    60,
];
const reservation = [];
for (const showCompany of [false, true]) {
    for (const showFullNames of [false, true]) {
        for (const labelLength of LABEL_LENGTHS) {
            const wrapsToTwoLines = listWrapsToTwoLines(showFullNames, labelLength);
            reservation.push({
                showCompany,
                showFullNames,
                labelLength,
                width: listWidth(showFullNames),
                wrapsToTwoLines,
                linePitch: listLinePitch(showCompany, wrapsToTwoLines),
            });
        }
    }
}

// A list's own HEIGHT, the formula all three reservations go through.
// A list is a stack of chips that each stand as tall as their own
// label needs, so the sweep is over (chips, wrapping chips) PAIRS and
// not over one pitch: the MIXED rows — a table where some chips wrap
// and others do not — are the ones a formula multiplying one pitch by
// a whole list gets wrong, and they are the reason this exists. The
// ends are swept with them: nothing wrapping, everything wrapping, an
// empty list, and counts outside the list on either side, which the
// clamp is what answers.
const CHIP_CASES = [
    [0, 0],
    [8, 0],
    [8, 1],
    [8, 3],
    [8, 7],
    [8, 8],
    [1, 1],
    [8, 99],
    [8, -1],
];
const reservedHeights = [];
for (const showCompany of [false, true]) {
    for (const [chipCount, wrappingChipCount] of CHIP_CASES) {
        reservedHeights.push({
            showCompany,
            chipCount,
            wrappingChipCount,
            height: listReservedHeight(chipCount, wrappingChipCount, showCompany),
        });
    }
}

const reservedHeightHeader = `;

// The third of what this file pins, generated the same way and read
// the same way: what a list of so many chips, so many of them
// wrapping, actually RESERVES. Regenerate it with the same script.
export const LIST_RESERVED_HEIGHT_FIXTURE = `;

const reservationHeader = `;

// The second half of what this file pins, generated the same way and
// read the same way: what a name list RESERVES beside a table, against
// its own Python twin. Regenerate it with the same script.
export const LIST_RESERVATION_FIXTURE = `;

writeFileSync(
    path.join(here, "visual_table_size_fixture.js"),
    header +
        JSON.stringify(rows, null, 4) +
        reservationHeader +
        JSON.stringify(reservation, null, 4) +
        reservedHeightHeader +
        JSON.stringify(reservedHeights, null, 4) +
        ";\n"
);
console.log(
    `wrote ${rows.length} size rows, ${reservation.length} reservation rows and` +
        ` ${reservedHeights.length} reserved-height rows to visual_table_size_fixture.js`
);
