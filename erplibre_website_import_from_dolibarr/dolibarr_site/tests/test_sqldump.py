import unittest

from ..model import SourceError
from ..sqldump import parse

COLS = (
    "rowid, fk_page, fk_website, pageurl, aliasalt, title, description,"
    " lang, image, keywords, status, date_creation, tms, import_key,"
    " grabbed_from, type_container, htmlheader, content, author_alias,"
    " allowed_in_frames"
)


def insert(rowid, ref, content, lang="", fk_page="null", kind="page"):
    return (
        "INSERT INTO llx_website_page(%s) VALUES(%d__+MAX_llx_website_page__,"
        " %s, __WEBSITE_ID__, '%s', '', 'T %s', '', '%s', '', '', '1',"
        " '2026-01-02 03:04:05', '2026-01-02 03:04:05', null, '', '%s', '',"
        " '%s', '', 0);\n"
        % (COLS, rowid, fk_page, ref, ref, lang, kind, content)
    )


HEADER = "-- File generated by Dolibarr 24.0.1 --;\n\n"
FOOTER = (
    "\n-- For Dolibarr v14+ --;\n"
    "UPDATE llx_website SET lang = 'en' WHERE rowid = __WEBSITE_ID__;\n"
    "UPDATE llx_website SET otherlang = 'fr,de' WHERE rowid ="
    " __WEBSITE_ID__;\n"
)


class SqldumpCases:
    def test_mysql_escapes_and_newline_token(self):
        body = r"a\'b\"c\\d\ne\tf\0g\Zh__N__i"
        dump = parse(HEADER + insert(1, "p", body) + FOOTER)
        self.assertEqual(
            dump.rows[0]["content"], "a'b\"c\\d\ne\tf\x00g\x1ah\ni"
        )

    def test_doubled_quote(self):
        dump = parse(HEADER + insert(1, "p", "it''s") + FOOTER)
        self.assertEqual(dump.rows[0]["content"], "it's")

    def test_columns_read_by_name(self):
        sql = (
            "INSERT INTO llx_website_page(pageurl, rowid, content,"
            " type_container) VALUES('x', 4__+MAX_llx_website_page__,"
            " 'body', 'page');\n"
        )
        row = parse(sql).rows[0]
        self.assertEqual((row["rowid"], row["pageurl"]), (4, "x"))
        self.assertEqual(row["content"], "body")

    def test_multiline_mode(self):
        sql = (
            "INSERT INTO llx_website_page(rowid, pageurl, htmlheader, content)"
            " VALUES(2__+MAX_llx_website_page__, 'p', /* new line */\n"
            "'<meta x>', /* new line */\n'<p>/* kept */ -- kept</p>');\n"
        )
        row = parse(sql).rows[0]
        self.assertEqual(row["htmlheader"], "<meta x>")
        self.assertEqual(row["content"], "<p>/* kept */ -- kept</p>")

    def test_home_mid_file_and_marker_gap(self):
        sql = (
            HEADER
            + "-- Page ID 6__+MAX_llx_website_page__ - Aliases home --;\n"
            + insert(7, "home", "h")
            + "UPDATE llx_website SET fk_default_home ="
            " 7__+MAX_llx_website_page__ WHERE rowid = __WEBSITE_ID__;\n"
            + insert(8, "about", "a")
            + FOOTER
        )
        dump = parse(sql)
        self.assertEqual(dump.home_id, 7)
        self.assertEqual([r["rowid"] for r in dump.rows], [7, 8])
        self.assertEqual(dump.version, "24.0.1")
        self.assertEqual((dump.lang, dump.otherlang), ("en", "fr,de"))

    def test_fk_page_and_website_id(self):
        dump = parse(
            insert(
                3, "t", "x", lang="fr", fk_page="2__+MAX_llx_website_page__"
            )
        )  # noqa: E501
        self.assertEqual(dump.rows[0]["fk_page"], 2)
        self.assertIsNone(dump.rows[0]["fk_website"])

    def test_unquoted_integers_are_ascii_and_bounded(self):
        dump = parse(
            insert(3, "t", "x", fk_page="\u0663")
            + insert(4, "u", "x", fk_page="1" * 26)
            + insert(5, "v", "x", fk_page="1" * 18)
            + insert(6, "w", "x", fk_page="\u0663__+MAX_llx_website_page__")
            + insert(
                7, "y", "x", fk_page="1" * 19 + "__+MAX_llx_website_page__"
            )
        )
        values = [row["fk_page"] for row in dump.rows]
        self.assertEqual(values[0], "\u0663")
        self.assertEqual(values[1], "1" * 26)
        self.assertEqual(values[2], int("1" * 18))
        self.assertIsInstance(values[3], str)
        self.assertIsInstance(values[4], str)

    def test_empty_lang_update(self):
        sql = insert(1, "p", "x") + (
            "UPDATE llx_website SET lang = 'en' WHERE rowid ="
            " __WEBSITE_ID__;\n"
            "UPDATE llx_website SET lang = '' WHERE rowid = __WEBSITE_ID__;\n"
        )
        self.assertEqual(parse(sql).lang, "")

    def test_crlf_and_bom_parse_like_lf(self):
        lf = HEADER + insert(1, "home", "a__N__b") + FOOTER
        crlf = "\ufeff" + lf.replace("\n", "\r\n")
        a, b = parse(lf), parse(crlf)
        self.assertEqual(a.rows, b.rows)
        self.assertEqual((a.lang, a.version), (b.lang, b.version))

    def test_unterminated_string_is_source_error(self):
        with self.assertRaises(SourceError):
            parse("INSERT INTO llx_website_page(rowid) VALUES('x);")

    def test_value_count_mismatch_is_source_error(self):
        with self.assertRaises(SourceError):
            parse("INSERT INTO llx_website_page(rowid, pageurl) VALUES(1);")


class TestSqldump(SqldumpCases, unittest.TestCase):
    pass
