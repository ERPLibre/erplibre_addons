"""Reader of the website_pages.sql file of a Dolibarr website export.

The SQL is never executed. A character reader splits statements outside
string literals, drops comments outside strings, then reads the INSERT
into llx_website_page by column name and the UPDATE llx_website rows.
"""

import dataclasses
import re

from .model import SourceError

_ESCAPES = {
    "0": "\x00",
    "n": "\n",
    "r": "\r",
    "t": "\t",
    "Z": "\x1a",
    "\\": "\\",
    "'": "'",
    '"': '"',
}
_INSERT = re.compile(
    r"^INSERT\s+INTO\s+llx_website_page\s*\((?P<cols>[^)]*)\)\s*VALUES\s*\(",
    re.I | re.S,
)
_HOME = re.compile(
    r"^UPDATE\s+llx_website\s+SET\s+fk_default_home\s*=\s*"
    r"(?P<id>\d+)__\+MAX_llx_website_page__",
    re.I,
)
_LANG = re.compile(
    r"^UPDATE\s+llx_website\s+SET\s+(?P<col>lang|otherlang)\s*=\s*", re.I
)
_VERSION = re.compile(r"^--\s*File generated by Dolibarr\s+(?P<v>\S+)", re.I)
_ROWID = re.compile(r"^([0-9]{1,18})__\+MAX_llx_website_page__$")
_INT = re.compile(r"^-?[0-9]{1,18}$")
_ATOM = re.compile(r"[^,)\s]+")


@dataclasses.dataclass
class SqlDump:
    version: str = ""
    rows: list = dataclasses.field(default_factory=list)
    home_id: int = None
    lang: str = ""
    otherlang: str = ""


def split_statements(text):
    """Split on ';' outside strings; return (statements, '--' comments)."""
    statements, comments, buf = [], [], []
    i, n, quote = 0, len(text), None
    while i < n:
        char = text[i]
        if quote:
            buf.append(char)
            if char == "\\" and i + 1 < n:
                buf.append(text[i + 1])
                i += 2
                continue
            if char == quote:
                if i + 1 < n and text[i + 1] == quote:
                    buf.append(quote)
                    i += 2
                    continue
                quote = None
            i += 1
            continue
        if char in "'\"":
            quote = char
            buf.append(char)
            i += 1
            continue
        if text.startswith("--", i):
            end = text.find("\n", i)
            end = n if end < 0 else end
            comments.append(text[i:end].rstrip("\r"))
            i = end
            continue
        if text.startswith("/*", i):
            end = text.find("*/", i + 2)
            if end < 0:
                raise SourceError(
                    "unterminated comment after statement %d" % len(statements)
                )
            i = end + 2
            continue
        if char == ";":
            sql = "".join(buf).strip()
            if sql:
                statements.append(sql)
            buf = []
            i += 1
            continue
        buf.append(char)
        i += 1
    if quote:
        raise SourceError(
            "unterminated string in statement %d" % (len(statements) + 1)
        )
    tail = "".join(buf).strip()
    if tail:
        statements.append(tail)
    return statements, comments


def _read_string(sql, i, number):
    """Decode the quoted literal starting at sql[i]; return (value, end)."""
    quote, out, i = sql[i], [], i + 1
    while i < len(sql):
        char = sql[i]
        if char == "\\" and i + 1 < len(sql):
            nxt = sql[i + 1]
            out.append(_ESCAPES.get(nxt, nxt))
            i += 2
            continue
        if char == quote:
            if i + 1 < len(sql) and sql[i + 1] == quote:
                out.append(quote)
                i += 2
                continue
            return "".join(out).replace("__N__", "\n"), i + 1
        out.append(char)
        i += 1
    raise SourceError("unterminated string in statement %d" % number)


def _atom(token):
    if token.lower() == "null" or token == "__WEBSITE_ID__":
        return None
    match = _ROWID.match(token)
    if match:
        return int(match.group(1))
    if _INT.match(token):
        return int(token)
    return token


def _skip_ws(sql, i):
    while i < len(sql) and sql[i].isspace():
        i += 1
    return i


def _read_values(sql, i, number):
    """Read a VALUES(...) list whose '(' ends just before sql[i]."""
    values = []
    while True:
        i = _skip_ws(sql, i)
        if i >= len(sql):
            raise SourceError("truncated VALUES in statement %d" % number)
        if sql[i] in "'\"":
            value, i = _read_string(sql, i, number)
        else:
            match = _ATOM.match(sql, i)
            if not match:
                raise SourceError("bad value in statement %d" % number)
            value, i = _atom(match.group(0)), match.end()
        values.append(value)
        i = _skip_ws(sql, i)
        if i < len(sql) and sql[i] == ",":
            i += 1
            continue
        if i < len(sql) and sql[i] == ")":
            return values
        raise SourceError("bad VALUES syntax in statement %d" % number)


def parse(text):
    """Parse the whole dump; unknown statements are ignored."""
    text = text.lstrip("\ufeff")
    statements, comments = split_statements(text)
    dump = SqlDump()
    for comment in comments:
        match = _VERSION.match(comment)
        if match and not dump.version:
            dump.version = match.group("v")
    for number, sql in enumerate(statements, start=1):
        insert = _INSERT.match(sql)
        if insert:
            cols = [c.strip() for c in insert.group("cols").split(",")]
            values = _read_values(sql, insert.end(), number)
            if len(values) != len(cols):
                raise SourceError(
                    "statement %d has %d columns and %d values"
                    % (number, len(cols), len(values))
                )
            dump.rows.append(dict(zip(cols, values)))
            continue
        home = _HOME.match(sql)
        if home:
            dump.home_id = int(home.group("id"))
            continue
        lang = _LANG.match(sql)
        if lang:
            i = _skip_ws(sql, lang.end())
            if i < len(sql) and sql[i] in "'\"":
                value, _end = _read_string(sql, i, number)
                setattr(dump, lang.group("col").lower(), value.strip())
    return dump
